// Extracts the authoritative product catalog from js/products.js and emits
//   supabase/catalog.json         - machine-readable copy (used by tooling / the Next app)
//   supabase/seed-products.sql    - idempotent seed for the Supabase `products` table
// and prints the *intended* pricing (base price per base unit -> per piece), which is
// the maths the new storefront uses. The legacy static site multiplied the base price
// by the piece count instead, overcharging cards/flyers/posters/stickers by ~100x.
//
// Usage: node scripts/extract-catalog.mjs

import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');

// js/products.js is a browser script: it assigns window.PRODUCTS.
globalThis.window = {};
const require = createRequire(import.meta.url);
require(path.join(root, 'js', 'products.js'));
const products = globalThis.window.PRODUCTS;

if (!Array.isArray(products) || products.length === 0) {
  console.error('Could not read window.PRODUCTS from js/products.js');
  process.exit(1);
}

// "/ 100 pcs" -> 100, "/ piece" -> 1, "/ sq.ft" -> 1, "/ 500 pcs" -> 500, "/ quote" -> 1
function baseQtyOf(baseUnit) {
  const m = String(baseUnit || '').match(/(\d[\d,]*)\s*(pcs|pieces|pc|units)/i);
  if (!m) return 1;
  return Number(m[1].replace(/,/g, '')) || 1;
}

const rows = products.map((p, i) => ({
  sort_order: i + 1,
  id: p.id,
  slug: p.slug,
  name: p.name,
  category: p.category,
  description: p.desc || '',
  image: p.image || '',
  base_price: p.basePrice,
  base_unit: p.baseUnit || '/ piece',
  options: p.options || [],
  quantities: p.quantities || [1],
  qty_discounts: p.qtyDiscounts || {},
  default_qty: p.defaultQty || 1,
  active: true,
  base_qty: baseQtyOf(p.baseUnit),
}));

fs.mkdirSync(path.join(root, 'supabase'), { recursive: true });
fs.writeFileSync(
  path.join(root, 'supabase', 'catalog.json'),
  JSON.stringify(rows, null, 2) + '\n',
  'utf8'
);

const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const json = (v) => q(JSON.stringify(v)) + '::jsonb';

const values = rows
  .map(
    (r) =>
      `  (${q(r.id)}, ${q(r.slug)}, ${q(r.name)}, ${q(r.category)}, ${q(r.description)}, ${q(
        r.image
      )}, ${r.base_price}, ${q(r.base_unit)}, ${json(r.options)}, ${json(r.quantities)}, ${json(
        r.qty_discounts
      )}, ${r.default_qty}, ${r.active ? 'true' : 'false'}, ${r.sort_order})`
  )
  .join(',\n');

const sql = `-- ═══════════════════════════════════════════════════════════════
-- Print Vatika — product catalog seed
-- Generated by scripts/extract-catalog.mjs from js/products.js
-- Run AFTER schema.sql. Safe to re-run (upsert by id).
-- ═══════════════════════════════════════════════════════════════

INSERT INTO products (
  id, slug, name, category, description, image,
  base_price, base_unit, options, quantities, qty_discounts,
  default_qty, active, sort_order
) VALUES
${values}
ON CONFLICT (id) DO UPDATE SET
  slug          = EXCLUDED.slug,
  name          = EXCLUDED.name,
  category      = EXCLUDED.category,
  description   = EXCLUDED.description,
  image         = EXCLUDED.image,
  base_price    = EXCLUDED.base_price,
  base_unit     = EXCLUDED.base_unit,
  options       = EXCLUDED.options,
  quantities    = EXCLUDED.quantities,
  qty_discounts = EXCLUDED.qty_discounts,
  default_qty   = EXCLUDED.default_qty,
  active        = EXCLUDED.active,
  sort_order    = EXCLUDED.sort_order,
  updated_at    = NOW();
`;

fs.writeFileSync(path.join(root, 'supabase', 'seed-products.sql'), sql, 'utf8');

// ── Report: the intended pricing, per product ────────────────────────
const rupee = (n) => '₹' + n.toFixed(2);
const lines = [];
lines.push('');
lines.push('Intended pricing (base price per base unit -> per piece).');
lines.push('This is what the new storefront will charge. The legacy site multiplied');
lines.push('the base price by the piece count instead (100x too much on cards etc).');
lines.push('');
lines.push(
  '  product'.padEnd(20) + 'base'.padEnd(10) + 'unit'.padEnd(13) + 'per pc'.padEnd(10) + 'qty: total after bulk discount'
);
lines.push('  ' + '-'.repeat(92));
for (const r of rows) {
  if (r.base_price === 0) {
    lines.push('  ' + r.name.padEnd(18) + 'quote'.padEnd(10) + r.base_unit.padEnd(13) + '-'.padEnd(10) + 'custom quote');
    continue;
  }
  const perPiece = r.base_price / r.base_qty;
  const totals = (r.quantities || []).map((qt) => {
    const disc = Object.entries(r.qty_discounts || {})
      .filter(([dq]) => qt >= Number(dq))
      .sort((a, b) => Number(b[0]) - Number(a[0]))[0]?.[1] ?? 1;
    return `${qt}=${rupee(perPiece * qt * disc)}`;
  });
  lines.push(
    '  ' +
      r.name.slice(0, 18).padEnd(18) +
      String(r.base_price).padEnd(10) +
      r.base_unit.padEnd(13) +
      rupee(perPiece).padEnd(10) +
      totals.join('  ')
  );
}
lines.push('');
fs.writeFileSync(path.join(root, 'supabase', 'pricing-preview.txt'), lines.join('\n'), 'utf8');
console.log(lines.join('\n'));
console.log('Wrote supabase/catalog.json');
console.log('Wrote supabase/seed-products.sql');
console.log('Wrote supabase/pricing-preview.txt');
